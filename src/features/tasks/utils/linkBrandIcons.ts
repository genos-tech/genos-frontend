// Hosts that belong to a brand living under a different registrable domain
// than the map key (so the suffix match can't reach them).
const HOST_ALIASES: Record<string, string> = {
    "youtu.be": "youtube.com",
    "discord.gg": "discord.com",
    "twitter.com": "x.com",
};

/**
 * Resolve a URL to a known brand icon, or null when the host isn't one we
 * recognize (the caller then shows the generic link glyph). Pure + exported
 * so the host-matching rules can be unit-tested.
 */
export const resolveLinkBrand = (url: string): BrandIcon | null => {
    let host: string;
    let pathname: string;
    try {
        const u = new URL(url);
        host = u.hostname.toLowerCase().replace(/^www\./, "");
        pathname = u.pathname;
    } catch {
        return null;
    }
    host = HOST_ALIASES[host] ?? host;

    // Docs and Sheets share docs.google.com; disambiguate by path.
    if (host === "docs.google.com") {
        return pathname.startsWith("/spreadsheets") ? GOOGLE_SHEETS : GOOGLE_DOCS;
    }

    // Exact host first, then a subdomain suffix match so e.g.
    // `acme.atlassian.net` still resolves to Jira.
    if (BRAND_ICONS[host]) return BRAND_ICONS[host];
    for (const domain in BRAND_ICONS) {
        if (host.endsWith(`.${domain}`)) return BRAND_ICONS[domain];
    }
    return null;
};

// sRGB relative luminance (WCAG) of a #RRGGBB color, 0 (black) … 1 (white).
const relativeLuminance = (hex: string): number => {
    const h = hex.replace("#", "");
    const chan = (i: number) => {
        const c = parseInt(h.slice(i, i + 2), 16) / 255;
        return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
    };
    return 0.2126 * chan(0) + 0.7152 * chan(2) + 0.0722 * chan(4);
};

/**
 * The color to paint a brand glyph in. Returns the brand's own color when
 * it has enough contrast against the current theme's icon background;
 * otherwise blends it toward white (dark mode) or black (light mode) so it
 * stays visible while keeping its hue. Near-achromatic marks (GitHub,
 * Notion, X) collapse to a legible grey this way instead of vanishing.
 */
export const brandColor = (brand: BrandIcon, isDark: boolean): string => {
    const h = brand.color.replace("#", "");
    const r = parseInt(h.slice(0, 2), 16);
    const g = parseInt(h.slice(2, 4), 16);
    const b = parseInt(h.slice(4, 6), 16);
    const bgL = isDark ? 0.02 : 0.98;
    const fgL = relativeLuminance(brand.color);
    const contrast = (Math.max(fgL, bgL) + 0.05) / (Math.min(fgL, bgL) + 0.05);
    if (contrast >= 2.2) return brand.color;
    const target = isDark ? 255 : 0;
    const t = isDark ? 0.5 : 0.45;
    const mix = (c: number) => Math.round(c + (target - c) * t);
    return `rgb(${mix(r)}, ${mix(g)}, ${mix(b)})`;
};
