import { useEffect, useMemo, useState } from "react";
import AddIcon from "@mui/icons-material/Add";
import DeleteOutlineIcon from "@mui/icons-material/DeleteOutline";
import EditIcon from "@mui/icons-material/Edit";
import {
    Box,
    Button,
    Chip,
    DialogContent,
    DialogTitle,
    Divider,
    IconButton,
    Input,
    Modal,
    ModalDialog,
    Option,
    Select,
    Stack,
    Tooltip,
    Typography,
} from "@mui/joy";

import { SprintMilestoneManagementState } from "../../../../hooks/tasks/useSprintMilestoneManagement";
import { Sprint } from "../types";

const STATUS_COLOR: Record<string, string> = {
    Open: "#0044c2",
    WIP: "#ff8c00",
    Pending: "#b900ff",
    Closed: "#1dc200",
    Deleted: "#94a3b8",
};

type Props = {
    open: boolean;
    onClose: () => void;
    projectId: number;
    useSM: SprintMilestoneManagementState;
};

const todayIso = () => new Date().toISOString().slice(0, 10);

const sprintBucket = (s: Sprint, today: string): "past" | "current" | "upcoming" => {
    if (s.endDate < today) return "past";
    if (s.startDate <= today && today <= s.endDate) return "current";
    return "upcoming";
};

const SprintRow = ({
    sprint,
    projectId,
    useSM,
    sprints,
}: {
    sprint: Sprint;
    projectId: number;
    useSM: SprintMilestoneManagementState;
    sprints: Sprint[];
}) => {
    const [editing, setEditing] = useState(false);
    const [name, setName] = useState(sprint.name);
    const [start, setStart] = useState(sprint.startDate);
    const [end, setEnd] = useState(sprint.endDate);
    const [error, setError] = useState<string | null>(null);

    useEffect(() => {
        setName(sprint.name);
        setStart(sprint.startDate);
        setEnd(sprint.endDate);
    }, [sprint.sprintId, sprint.name, sprint.startDate, sprint.endDate]);

    const milestonesInSprint = useMemo(() => {
        const list = useSM.projectMilestones[projectId] ?? [];
        return list.filter((m) => m.sprintId === sprint.sprintId);
    }, [useSM.projectMilestones, projectId, sprint.sprintId]);

    const otherSprints = useMemo(
        () => sprints.filter((s) => s.sprintId !== sprint.sprintId),
        [sprints, sprint.sprintId]
    );

    const save = async () => {
        setError(null);
        if (!start || !end || end < start) {
            setError("End date must be on or after start date.");
            return;
        }
        const res = await useSM.updateExistingSprint({
            sprintId: sprint.sprintId,
            name,
            startDate: start,
            endDate: end,
        });
        if (res) {
            setEditing(false);
        } else {
            setError("Failed to update sprint (overlap?).");
        }
    };

    const remove = async () => {
        if (!confirm(`Delete "${sprint.name}"? This cannot be undone.`)) return;
        await useSM.removeSprint(sprint.sprintId, projectId);
    };

    return (
        <Box
            sx={{
                p: 1.25,
                borderRadius: 8,
                border: "1px solid",
                borderColor: "neutral.outlinedBorder",
                bgcolor: "background.surface",
            }}
        >
            <Stack direction="row" spacing={1} alignItems="center">
                {editing ? (
                    <Input
                        size="sm"
                        value={name}
                        onChange={(e) => setName(e.target.value)}
                        sx={{ flex: 1 }}
                    />
                ) : (
                    <Typography level="title-sm" sx={{ flex: 1 }}>
                        {sprint.name}
                    </Typography>
                )}
                <Chip size="sm" variant="soft" color="neutral">
                    #{sprint.sequenceNumber}
                </Chip>
                {sprint.isAutoGenerated && (
                    <Chip size="sm" variant="soft" color="primary">
                        Auto
                    </Chip>
                )}
                {!editing && (
                    <Tooltip title="Edit" size="sm">
                        <IconButton size="sm" variant="plain" onClick={() => setEditing(true)}>
                            <EditIcon sx={{ fontSize: 16 }} />
                        </IconButton>
                    </Tooltip>
                )}
                <Tooltip title="Delete" size="sm">
                    <IconButton size="sm" variant="plain" color="danger" onClick={remove}>
                        <DeleteOutlineIcon sx={{ fontSize: 16 }} />
                    </IconButton>
                </Tooltip>
            </Stack>

            <Stack direction="row" spacing={1} alignItems="center" sx={{ mt: 1 }}>
                {editing ? (
                    <>
                        <Input
                            type="date"
                            size="sm"
                            value={start}
                            onChange={(e) => setStart(e.target.value)}
                        />
                        <Typography level="body-xs">→</Typography>
                        <Input
                            type="date"
                            size="sm"
                            value={end}
                            onChange={(e) => setEnd(e.target.value)}
                        />
                        <Button size="sm" onClick={save}>
                            Save
                        </Button>
                        <Button
                            size="sm"
                            variant="plain"
                            color="neutral"
                            onClick={() => {
                                setEditing(false);
                                setName(sprint.name);
                                setStart(sprint.startDate);
                                setEnd(sprint.endDate);
                                setError(null);
                            }}
                        >
                            Cancel
                        </Button>
                    </>
                ) : (
                    <Typography level="body-xs" sx={{ color: "neutral.500" }}>
                        {sprint.startDate} → {sprint.endDate}
                    </Typography>
                )}
            </Stack>

            {error && (
                <Typography level="body-xs" color="danger" sx={{ mt: 0.5 }}>
                    {error}
                </Typography>
            )}

            {milestonesInSprint.length > 0 && (
                <Box sx={{ mt: 1.25, pl: 1, borderLeft: "2px solid", borderColor: "divider" }}>
                    <Typography level="body-xs" sx={{ color: "neutral.500", mb: 0.5 }}>
                        Milestones
                    </Typography>
                    <Stack spacing={0.5}>
                        {milestonesInSprint.map((m) => (
                            <Stack
                                key={m.milestoneId}
                                direction="row"
                                spacing={1}
                                alignItems="center"
                            >
                                <Typography level="body-sm" sx={{ flex: 1 }}>
                                    {m.title}
                                </Typography>
                                <Chip
                                    size="sm"
                                    variant="soft"
                                    sx={{
                                        color: STATUS_COLOR[m.status as string] ?? "#94a3b8",
                                        backgroundColor: `${STATUS_COLOR[m.status as string] ?? "#94a3b8"}1A`,
                                    }}
                                >
                                    {m.status}
                                </Chip>
                                <Select
                                    size="sm"
                                    placeholder="Move to..."
                                    value={null}
                                    onChange={async (_, v) => {
                                        if (v === undefined || v === null) return;
                                        const target = v === -1 ? null : Number(v);
                                        await useSM.moveMilestone(
                                            m.milestoneId,
                                            target,
                                            projectId
                                        );
                                    }}
                                    sx={{ minWidth: 160 }}
                                >
                                    <Option value={-1}>No sprint</Option>
                                    {otherSprints.map((s) => (
                                        <Option key={s.sprintId} value={s.sprintId}>
                                            {s.name}
                                        </Option>
                                    ))}
                                </Select>
                            </Stack>
                        ))}
                    </Stack>
                </Box>
            )}
        </Box>
    );
};

export const SprintManagerDialog = ({ open, onClose, projectId, useSM }: Props) => {
    const [showAdd, setShowAdd] = useState(false);
    const [adhocName, setAdhocName] = useState("");
    const [adhocStart, setAdhocStart] = useState(todayIso());
    const [adhocEnd, setAdhocEnd] = useState(todayIso());
    const [adhocError, setAdhocError] = useState<string | null>(null);
    const [creating, setCreating] = useState(false);

    const today = todayIso();
    const sprints = useSM.projectSprints[projectId] ?? [];

    const grouped = useMemo(() => {
        const out: Record<"past" | "current" | "upcoming", Sprint[]> = {
            past: [],
            current: [],
            upcoming: [],
        };
        for (const s of sprints) out[sprintBucket(s, today)].push(s);
        return out;
    }, [sprints, today]);

    useEffect(() => {
        if (!open) return;
        // Refresh sprints + milestones on open so the user always sees
        // the latest state, including newly auto-rolled rows.
        useSM.loadSprintsForProject(projectId);
        useSM.loadMilestonesForProject(projectId, {
            statuses: ["Open", "WIP", "Pending", "Closed"],
        });
    }, [open, projectId]);

    const submitAdhoc = async () => {
        setAdhocError(null);
        if (!adhocName || !adhocStart || !adhocEnd || adhocEnd < adhocStart) {
            setAdhocError("Name, start, and end (>= start) are all required.");
            return;
        }
        setCreating(true);
        const created = await useSM.createNewSprint({
            projectId,
            name: adhocName,
            startDate: adhocStart,
            endDate: adhocEnd,
        });
        setCreating(false);
        if (created) {
            setShowAdd(false);
            setAdhocName("");
            setAdhocStart(todayIso());
            setAdhocEnd(todayIso());
        } else {
            setAdhocError("Could not create sprint (overlaps an existing sprint?).");
        }
    };

    const renderSection = (title: string, items: Sprint[]) => (
        <Box>
            <Typography
                level="body-xs"
                sx={{
                    fontWeight: 600,
                    textTransform: "uppercase",
                    letterSpacing: "0.08em",
                    color: "neutral.500",
                    mb: 0.75,
                }}
            >
                {title} ({items.length})
            </Typography>
            <Stack spacing={1}>
                {items.length === 0 ? (
                    <Typography level="body-xs" sx={{ color: "neutral.400" }}>
                        None.
                    </Typography>
                ) : (
                    items.map((s) => (
                        <SprintRow
                            key={s.sprintId}
                            sprint={s}
                            projectId={projectId}
                            useSM={useSM}
                            sprints={sprints}
                        />
                    ))
                )}
            </Stack>
        </Box>
    );

    return (
        <Modal open={open} onClose={onClose}>
            <ModalDialog sx={{ minWidth: 640, maxHeight: "85vh" }}>
                <DialogTitle>Manage sprints</DialogTitle>
                <Divider />
                <DialogContent sx={{ overflowY: "auto" }}>
                    <Stack spacing={2.5} sx={{ pt: 1, pb: 1 }}>
                        <Stack direction="row" spacing={1} alignItems="center">
                            <Typography level="body-sm" sx={{ flex: 1 }}>
                                Plan upcoming sprints, rename, shift dates, or insert ad-hoc ones.
                            </Typography>
                            <Button
                                size="sm"
                                startDecorator={<AddIcon />}
                                onClick={() => setShowAdd((v) => !v)}
                            >
                                Add custom sprint
                            </Button>
                        </Stack>

                        {showAdd && (
                            <Box
                                sx={{
                                    p: 1.5,
                                    borderRadius: 8,
                                    border: "1px solid",
                                    borderColor: "neutral.outlinedBorder",
                                    bgcolor: "background.level1",
                                }}
                            >
                                <Stack spacing={1}>
                                    <Input
                                        size="sm"
                                        placeholder="Sprint name"
                                        value={adhocName}
                                        onChange={(e) => setAdhocName(e.target.value)}
                                    />
                                    <Stack direction="row" spacing={1} alignItems="center">
                                        <Input
                                            type="date"
                                            size="sm"
                                            value={adhocStart}
                                            onChange={(e) => setAdhocStart(e.target.value)}
                                        />
                                        <Typography level="body-xs">→</Typography>
                                        <Input
                                            type="date"
                                            size="sm"
                                            value={adhocEnd}
                                            onChange={(e) => setAdhocEnd(e.target.value)}
                                        />
                                        <Button size="sm" onClick={submitAdhoc} loading={creating}>
                                            Create
                                        </Button>
                                    </Stack>
                                    {adhocError && (
                                        <Typography level="body-xs" color="danger">
                                            {adhocError}
                                        </Typography>
                                    )}
                                </Stack>
                            </Box>
                        )}

                        {renderSection("Current", grouped.current)}
                        {renderSection("Upcoming", grouped.upcoming)}
                        {renderSection("Past", grouped.past)}
                    </Stack>
                </DialogContent>
            </ModalDialog>
        </Modal>
    );
};
