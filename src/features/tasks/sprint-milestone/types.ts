import { UserProps } from "../../../types/admin";

export type SprintStatus = "upcoming" | "active" | "completed" | "archived";

export type Sprint = {
    sprintId: number;
    projectId: number;
    teamId: number | string | null;
    name: string;
    sequenceNumber: number;
    startDate: string;
    endDate: string;
    status: SprintStatus;
    isAutoGenerated: boolean;
    isDeleted: boolean;
    tsCreatedAt: string;
    tsUpdatedAt: string;
};

export type SprintConfig = {
    projectId: number;
    teamId: number | string | null;
    durationDays: number;
    anchorDate: string;
    autoRoll: boolean;
    upcomingHorizon: number;
};

export type ProjectSprintsResponse = {
    sprints: Sprint[];
    today: string;
};

export type MilestoneStatus = "Open" | "WIP" | "Pending" | "Closed" | "Deleted";

export type MilestoneAssignee = {
    userId: number | string | null;
    username: string | null;
    firstName: string | null;
    lastName: string | null;
    email: string | null;
    profileImageUrl: string | null;
};

export type Milestone = {
    milestoneId: number;
    // `taskId` is the milestone's backing TaskMaster row. The preview
    // pane uses it to load comments, notes, and attachments through the
    // same task-* endpoints a normal task uses, so a milestone behaves
    // like a "root task" with extra metadata (sprint linkage, multi
    // assignees). Null only for very legacy rows; the backend lazy-
    // backfills on the next read.
    taskId: number | null;
    // Human-readable id from the backing task's `display_id`
    // ("<code>-<n>"). Lets table / preview surfaces render the
    // friendly id without an extra lookup. Null for legacy
    // milestones whose backing task hasn't been backfilled yet.
    displayId?: string | null;
    // Chat-thread origin (set when the milestone was created from a
    // DM/GM/MDM thread), read off the backing task row. Drives the
    // milestone preview's "Check thread" button. chatId/threadId are
    // v3 UUIDs (strings); legacy rows may carry numeric strings.
    chatType?: number | null;
    chatId?: string | null;
    threadId?: string | null;
    projectId: number;
    teamId: number | string | null;
    sprintId: number | null;
    // Grouping folder (MIP-847); null / absent = unfiled. Independent of the
    // sprint: a milestone has both.
    folderId?: number | null;
    reporterId: number | string | null;
    // Resolved reporter user object (same shape as MilestoneAssignee)
    // so the milestone preview can render the reporter without an
    // extra team-member lookup. Optional for backwards compat.
    reporter?: MilestoneAssignee | null;
    title: string;
    description: unknown | null;
    status: MilestoneStatus | string;
    statusCode: number | null;
    priority: string | null;
    priorityCode: number | null;
    effortLevel?: string | null;
    effortLevelCode?: number | null;
    startDate: string | null;
    dueDate: string | null;
    tags: unknown | null;
    // External links shown by the milestone preview's URL/Link section.
    // Mirrors `TaskProps.links` shape: `{ id, url, title, isGitHub }[]`.
    // Stored as `JSONField` server-side; expressed as `unknown` here to
    // match the existing `tags` convention (the consumer narrows it).
    links?: unknown | null;
    // Custom-field value map, read off the BACKING TASK row (the single
    // source of truth for these — see the API's _serialize_milestone).
    customFieldValues?: Record<string, string | string[]> | null;
    // Collaborators, read off the BACKING TASK row (same source-of-truth
    // pattern as customFieldValues). Same embedded-user shape as reporter.
    collaborators?: MilestoneAssignee[];
    isDeleted: boolean;
    tsCreatedAt: string;
    tsUpdatedAt: string;
    assignees: MilestoneAssignee[];
    tasksTotal?: number;
    tasksClosed?: number;
};

// A named group of milestones within a project (MIP-847).
export type MilestoneFolder = {
    folderId: number;
    projectId: number;
    name: string;
    sortOrder: number;
    tsCreatedAt: string;
    tsUpdatedAt: string;
};

export type ProjectMilestoneFoldersResponse = {
    folders: MilestoneFolder[];
};

/** A milestone the user starred (MIP-1053), as the Favorites list shows it. */
export type MilestoneFavorite = {
    milestoneId: number;
    taskId: number | null;
    displayId: string | null;
    title: string;
    status: string;
    projectId: number;
    /** Empty on a star just added in this tab, until the list is re-read. */
    projectName: string;
    teamId: string | null;
    tsFavorited: string;
    /** Null until the user opens it after starring. */
    tsLastOpened: string | null;
};

export type MilestoneFavoritesResponse = {
    favorites: MilestoneFavorite[];
};

export type ProjectMilestonesResponse = {
    milestones: Milestone[];
};

export type MilestoneResponse = {
    milestone: Milestone;
};

export type SprintConfigResponse = {
    config: SprintConfig | null;
};

export type SprintResponse = {
    sprint: Sprint;
};

