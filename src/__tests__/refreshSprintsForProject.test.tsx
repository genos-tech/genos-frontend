/**
 * `refreshSprintsForProject` is `loadSprintsForProject` that says whether it
 * worked (MIP-970 step 5). `loadSprintsForProject` resolves `[]` both for a
 * project with no sprints and for a failed request, so the change-driven
 * refresh could not tell them apart and would have recorded a token for a load
 * that never happened.
 */

import { act, renderHook } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";

import { useSprintMilestoneManagement } from "../hooks/tasks/useSprintMilestoneManagement";

const loadProjectSprintsMock = vi.fn();
vi.mock("../features/tasks/sprint-milestone/services", async (importOriginal) => ({
    ...(await importOriginal<object>()),
    loadProjectSprints: (...args: unknown[]) => loadProjectSprintsMock(...args),
}));

const sprint = {
    sprintId: 1,
    projectId: 1,
    teamId: null,
    name: "Sprint 1",
    sequenceNumber: 1,
    startDate: "2026-08-01",
    endDate: "2026-08-14",
    status: "active",
    isAutoGenerated: true,
    isDeleted: false,
    tsCreatedAt: "2026-08-01T00:00:00Z",
    tsUpdatedAt: "2026-08-01T00:00:00Z",
};

beforeEach(() => loadProjectSprintsMock.mockReset());

describe("refreshSprintsForProject", () => {
    const run = async (answer: unknown) => {
        loadProjectSprintsMock.mockResolvedValueOnce(answer);
        const hook = renderHook(() => useSprintMilestoneManagement("tok"));
        let ok: boolean | undefined;
        let legacy: unknown;
        await act(async () => {
            ok = await hook.result.current.refreshSprintsForProject(1);
        });
        loadProjectSprintsMock.mockResolvedValueOnce(answer);
        await act(async () => {
            legacy = await hook.result.current.loadSprintsForProject(1);
        });
        return { ok, legacy, hook };
    };

    it("true when the sprints loaded, and the state is updated as before", async () => {
        const { ok, hook } = await run({ sprints: [sprint], today: "2026-08-10" });
        expect(ok).toBe(true);
        expect(hook.result.current.currentSprint?.sprintId).toBe(1);
    });

    it("true for a project that really has no sprints", async () => {
        const { ok, legacy } = await run({ sprints: [], today: "2026-08-10" });
        expect(ok).toBe(true);
        expect(legacy).toEqual([]);
    });

    it("false for a failed request, while loadSprintsForProject still answers []", async () => {
        const { ok, legacy } = await run(undefined);
        expect(ok).toBe(false);
        expect(legacy).toEqual([]);
    });
});
